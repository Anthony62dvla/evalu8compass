/*
 * Regenerates public/js/icons.js from Tabler Icons (MIT).
 * 1. npm pack @tabler/icons@3.19.0 && tar xzf tabler-icons-*.tgz   (gives ./package)
 * 2. node scripts/build-icons.js path/to/package
 * Add a name to NAMES to bundle another icon (browse them at tabler.io/icons).
 */
const fs = require("fs"), path = require("path");
const NAMES = ["shield-check","users","book","trending-up","calendar-check","heart-handshake","horse-toy","school","compass","clipboard-check",
  "circle-check","circle-half-2","circle-x","help-circle","circle-minus","sparkles","copy","device-floppy","refresh","layout-navbar-collapse",
  "filter","list-check","broadcast","lock","presentation","link","logout","file-upload","file-text","message-circle","target","file-export",
  "qrcode","user","login","arrow-right","alert-triangle","scale","eye","checks","building","chevron-down","chalkboard","user-heart","tool",
  "briefcase","building-community","clipboard-list","arrows-diff","photo","x","player-play","bulb","home","users-group","list-details"];
const dir = path.join(process.argv[2] || "package", "icons", "outline");
const out = {};
for (const n of NAMES) {
  const svg = fs.readFileSync(path.join(dir, n + ".svg"), "utf8");
  out[n] = (svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/) || [])[1]
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, "").replace(/\s+/g, " ").trim();
}
const js = `/* Icons: Tabler Icons v3.19.0 (MIT licence, see /licences/tabler-icons-LICENSE.txt). Generated by scripts/build-icons.js */
(function (root) {
  const P = ${JSON.stringify(out)};
  /** icon("book", 24) → inline SVG string. Decorative by default (aria-hidden). */
  function icon(name, size, cls) {
    const s = size || 20;
    return '<svg class="ic' + (cls ? " " + cls : "") + '" width="' + s + '" height="' + s + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + (P[name] || "") + "</svg>";
  }
  /** Replaces every <i data-icon="name" data-size="20"></i> inside el with its SVG. */
  function hydrate(el) {
    (el || document).querySelectorAll("i[data-icon]").forEach(function (i) {
      i.insertAdjacentHTML("afterend", icon(i.dataset.icon, Number(i.dataset.size) || 20, i.className));
      i.remove();
    });
  }
  root.HWWD = Object.assign(root.HWWD || {}, { icon: icon, hydrateIcons: hydrate });
  if (typeof document !== "undefined") hydrate(document);
})(window);
`;
fs.writeFileSync(path.join(__dirname, "..", "public", "js", "icons.js"), js);
console.log("Wrote public/js/icons.js with", NAMES.length, "icons");
