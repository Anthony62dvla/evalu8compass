  /* ================= HTML (screen and PDF) ================= */
  function cellHTML(c) {
    if (c == null) return "<td></td>";
    if (typeof c !== "object") return `<td>${esc(c)}</td>`;
    const sub = c.sub ? String(c.sub).split("\n").map(l => `<span class="sub">${esc(l)}</span>`).join("") : "";
    if (c.num) return `<td class="num">${esc(c.text)}</td>`;
    if (c.tone) return `<td><span class="tone tone-${c.tone}">${esc(c.text)}</span>${sub}</td>`;
    return `<td>${c.muted ? `<span class="pmuted">${esc(c.text)}</span>` : esc(c.text)}${sub}</td>`;
  }
  function renderHTML(m) {
    return m.blocks.map(b => {
      switch (b.t) {
        case "cover": return `<header class="rcover"><div class="rcover-top"><div class="rcover-logo">${b.logo ? `<img src="${esc(b.logo)}" alt="">` : I("school", 36)}</div>
          <div><div class="rcover-kicker">${esc(b.kicker)}</div><div class="rcover-title">${esc(b.title)}</div><div class="rcover-school">${esc(b.school)}</div></div></div>
          <div class="rmeta">${b.meta.filter(x => x[1]).map(([k, v]) => `<div><b>${esc(k)}</b>${esc(v)}</div>`).join("")}</div></header>`;
        case "h1": return `<h1${b.pb ? ' class="pb"' : ""}>${esc(b.text)}</h1>`;
        case "h2": return `<h2>${esc(b.text)}</h2>`;
        case "p": return `<p class="${b.muted ? "pmuted" : ""}">${b.strong ? `<b>${esc(b.text)}</b>` : esc(b.text)}</p>`;
        case "stats": return `<div class="rstats">${b.items.map(([v, l]) => `<div class="rstat"><b>${esc(v)}</b><span>${esc(l)}</span></div>`).join("")}</div>`;
        case "table": return `<div class="rtable-wrap"><table class="rtable"><colgroup>${b.widths.map(w => `<col style="width:${w}%">`).join("")}</colgroup><thead><tr>${b.head.map(h => `<th>${esc(h)}</th>`).join("")}</tr></thead><tbody>${b.rows.map(r => `<tr>${r.map(cellHTML).join("")}</tr>`).join("")}</tbody></table></div>`;
        case "list": return `<ul class="rlist">${b.items.map(i => `<li>${esc(i)}</li>`).join("")}</ul>`;
        case "note": return `<p class="rnote">${esc(b.text)}</p>`;
        default: return "";
      }
    }).join("") + `<div class="rfoot"><span>Evalu8 Compass · ${esc(m.school)}</span><span>Generated ${esc(today())}</span></div>`;
  }

  /* ================= Word (.docx) ================= */
  function loadDocx() {
    if (window.docx) return Promise.resolve(window.docx);
    return new Promise((res, rej) => {
      const s = document.createElement("script");
      s.src = "vendor/docx-9.5.1.umd.js"; s.onload = () => res(window.docx); s.onerror = () => rej(new Error("Couldn't load the Word builder."));
      document.head.append(s);
    });
  }
  const TONE = { met: ["EAF3DE", "27500A"], done: ["EAF3DE", "27500A"], part: ["FAEEDA", "633806"], doing: ["FAEEDA", "633806"], no: ["FCEBEB", "791F1F"], overdue: ["FCEBEB", "791F1F"], na: ["F1EFE8", "444441"], todo: ["F1EFE8", "444441"], ai: ["EEEDFE", "3C3489"] };
  function dataUrlBytes(u) { const b = atob(u.split(",")[1]); const a = new Uint8Array(b.length); for (let i = 0; i < b.length; i++) a[i] = b.charCodeAt(i); return a; }

  async function toDocx(m) {
    const D = await loadDocx();
    const W = 9638; // A4 width minus 20 mm margins, in twentieths of a point
    const run = (text, o) => new D.TextRun({ text: String(text == null ? "" : text), ...(o || {}) });
    const paras = (text, o, ro) => String(text == null ? "" : text).split("\n").map(line => new D.Paragraph({ children: [run(line, ro)], spacing: { after: 80 }, ...(o || {}) }));
    const border = { style: D.BorderStyle.SINGLE, size: 4, color: "CFDDD8" };
    const borders = { top: border, bottom: border, left: border, right: border, insideHorizontal: border, insideVertical: border };
    const dxa = ws => { const tot = ws.reduce((a, b) => a + b, 0); const out = ws.map(w => Math.floor(W * w / tot)); out[out.length - 1] += W - out.reduce((a, b) => a + b, 0); return out; };
    const cellFor = (c, width, header) => {
      const o = { width: { size: width, type: D.WidthType.DXA }, margins: { top: 60, bottom: 60, left: 100, right: 100 } };
      if (header) return new D.TableCell({ ...o, shading: { type: D.ShadingType.CLEAR, color: "auto", fill: "04342C" }, children: [new D.Paragraph({ children: [run(c, { bold: true, color: "FFFFFF", size: 18 })] })] });
      const cc = c && typeof c === "object" ? c : { text: c == null ? "" : String(c) };
      const kids = [];
      const t = TONE[cc.tone];
      kids.push(...paras(cc.text, cc.num ? { alignment: D.AlignmentType.RIGHT } : null, { size: 18, bold: !!t, color: t ? t[1] : cc.muted ? "4B5E59" : "102521" }));
      if (cc.sub) kids.push(...paras(cc.sub, null, { size: 16, color: "4B5E59" }));
      return new D.TableCell({ ...o, ...(t ? { shading: { type: D.ShadingType.CLEAR, color: "auto", fill: t[0] } } : {}), children: kids });
    };
    const kids = [];
    for (const b of m.blocks) {
      if (b.t === "cover") {
        if (b.logo && /^data:image\/(png|jpeg)/.test(b.logo)) {
          kids.push(new D.Paragraph({ children: [new D.ImageRun({ type: b.logo.includes("png") ? "png" : "jpg", data: dataUrlBytes(b.logo), transformation: { width: 72, height: 72 } })], spacing: { after: 120 } }));
        }
        kids.push(new D.Paragraph({ children: [run(b.kicker.toUpperCase(), { bold: true, color: "0F6E56", size: 18 })], spacing: { after: 60 } }));
        kids.push(new D.Paragraph({ children: [run(b.title, { bold: true, color: "04342C", size: 52 })], spacing: { after: 60 } }));
        kids.push(new D.Paragraph({ children: [run(b.school, { bold: true, size: 30 })], spacing: { after: 200 } }));
        b.meta.filter(x => x[1]).forEach(([k, v]) => kids.push(new D.Paragraph({ children: [run(k + ": ", { bold: true, color: "4B5E59" }), run(v)], spacing: { after: 40 } })));
        kids.push(new D.Paragraph({ border: { bottom: { style: D.BorderStyle.SINGLE, size: 12, color: "0F6E56", space: 4 } }, spacing: { after: 200 }, children: [] }));
      } else if (b.t === "h1") kids.push(new D.Paragraph({ heading: D.HeadingLevel.HEADING_1, pageBreakBefore: !!b.pb, children: [run(b.text)] }));
      else if (b.t === "h2") kids.push(new D.Paragraph({ heading: D.HeadingLevel.HEADING_2, children: [run(b.text)] }));
      else if (b.t === "p") kids.push(...paras(b.text, null, { color: b.muted ? "4B5E59" : undefined, bold: !!b.strong }));
      else if (b.t === "note") kids.push(...paras(b.text, { shading: { type: D.ShadingType.CLEAR, color: "auto", fill: "E8F5F0" }, spacing: { before: 120, after: 120 } }, { italics: true, size: 18, color: "4B5E59" }));
      else if (b.t === "list") b.items.forEach(i => kids.push(new D.Paragraph({ numbering: { reference: "bullets", level: 0 }, spacing: { after: 60 }, children: [run(i)] })));
      else if (b.t === "stats") {
        const ws = dxa(b.items.map(() => 1));
        kids.push(new D.Table({ width: { size: W, type: D.WidthType.DXA }, columnWidths: ws, borders: { ...borders, insideVertical: { style: D.BorderStyle.SINGLE, size: 24, color: "FFFFFF" }, top: { style: D.BorderStyle.NONE }, bottom: { style: D.BorderStyle.NONE }, left: { style: D.BorderStyle.NONE }, right: { style: D.BorderStyle.NONE } },
          rows: [new D.TableRow({ children: b.items.map(([v, l], i) => new D.TableCell({ width: { size: ws[i], type: D.WidthType.DXA }, shading: { type: D.ShadingType.CLEAR, color: "auto", fill: "E8F5F0" }, margins: { top: 100, bottom: 100, left: 120, right: 120 },
            children: [new D.Paragraph({ children: [run(v, { bold: true, size: 32, color: "04342C" })] }), new D.Paragraph({ children: [run(l, { size: 16, color: "4B5E59" })] })] })) })] }));
        kids.push(new D.Paragraph({ children: [], spacing: { after: 120 } }));
      } else if (b.t === "table") {
        const ws = dxa(b.widths);
        kids.push(new D.Table({ width: { size: W, type: D.WidthType.DXA }, columnWidths: ws, borders,
          rows: [new D.TableRow({ tableHeader: true, children: b.head.map((h, i) => cellFor(h, ws[i], true)) }), ...b.rows.map(r => new D.TableRow({ cantSplit: true, children: r.map((c, i) => cellFor(c, ws[i], false)) }))] }));
        kids.push(new D.Paragraph({ children: [], spacing: { after: 160 } }));
      }
    }
    const doc = new D.Document({
      creator: "Evalu8 Compass", title: m.title, description: "School self-evaluation report",
      styles: {
        default: { document: { run: { font: "Arial", size: 20, color: "102521" } } },
        paragraphStyles: [
          { id: "Heading1", name: "Heading 1", basedOn: "Normal", next: "Normal", quickFormat: true, run: { font: "Arial", size: 32, bold: true, color: "04342C" }, paragraph: { spacing: { before: 360, after: 160 }, outlineLevel: 0, border: { bottom: { style: D.BorderStyle.SINGLE, size: 12, color: "0F6E56", space: 4 } } } },
          { id: "Heading2", name: "Heading 2", basedOn: "Normal", next: "Normal", quickFormat: true, run: { font: "Arial", size: 24, bold: true, color: "04342C" }, paragraph: { spacing: { before: 240, after: 100 }, outlineLevel: 1 } },
        ],
      },
      numbering: { config: [{ reference: "bullets", levels: [{ level: 0, format: D.LevelFormat.BULLET, text: "•", alignment: D.AlignmentType.LEFT, style: { paragraph: { indent: { left: 540, hanging: 270 } } } }] }] },
      sections: [{
        properties: { page: { size: { width: 11906, height: 16838 }, margin: { top: 1134, bottom: 1134, left: 1134, right: 1134 } } },
        footers: { default: new D.Footer({ children: [new D.Paragraph({ alignment: D.AlignmentType.RIGHT, children: [run(`Evalu8 Compass · ${m.school} · page `, { size: 16, color: "4B5E59" }), new D.TextRun({ children: [D.PageNumber.CURRENT], size: 16, color: "4B5E59" })] })] }) },
        children: kids,
      }],
    });
    return D.Packer.toBlob(doc);
  }

